HOW_TO_READ = """
**這個儀表板在做什麼**

用價格、利率、利差等『代理指標』，觀察美國市場的資金與壓力狀況。
它**看不到**基金申購贖回的真實金額，所以所有結論都是從價格推論，不是看到錢真的移動。

**建議的看法順序**

1. **先看壓力指標**：高收益債利差、VIX、MOVE 是否同時往壞的方向急變。只有一個指標異常，多半是局部事件。
2. **再看輪動**：股票、長債、類現金、黃金誰強誰弱，判斷資金偏向進攻還是防禦。
3. **最後看中期現金與流動性**：貨幣基金、準備金、TGA 的趨勢，用來理解大環境，不用來判斷單日行情。

**常見誤區**

- 兩個指標同時變動，不等於其中一個造成另一個。
- 殖利率下降不一定是資金流入債市，也可能是降息預期。
- 週頻資料（準備金、TGA、貨幣基金、存款）會落後數日，不能拿來對單日事件。
"""

